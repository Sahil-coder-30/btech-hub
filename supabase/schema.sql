-- ---------- Academic catalogue ----------

create table if not exists public.branches (
  code        text primary key,
  name        text not null,
  sort_order  int  not null default 0
);

create table if not exists public.subjects (
  id            bigint generated by default as identity primary key,
  title         text not null,                 -- original display title
  primary_code  text,                          -- e.g. BCS301, null for electives
  codes         jsonb not null default '[]',   -- every code found in the title
  options       jsonb not null default '[]',   -- either/or choices, e.g. Physics / Chemistry
  credits       numeric(3,1) not null,
  kind          text not null default 'theory' check (kind in ('theory','lab','project')),
  year          smallint not null check (year between 1 and 4),
  semester      smallint not null check (semester between 1 and 8),
  branch_code   text,                          -- null = common first-year subject
  sort_order    int not null default 0
);
create index if not exists subjects_lookup_idx on public.subjects (year, semester, branch_code);
create index if not exists subjects_code_idx   on public.subjects (primary_code);

create table if not exists public.resources (
  id             bigint generated by default as identity primary key,
  subject_code   text,
  subject_title  text not null,
  year           smallint not null check (year between 1 and 4),
  semester       smallint not null check (semester between 1 and 8),
  branch_code    text,
  type           text not null check (type in ('notes','pyq','lecture','imp_question','other')),
  label          text not null,
  url            text,                         -- null = coming soon
  created_at     timestamptz not null default now()
);
create index if not exists resources_lookup_idx on public.resources (year, semester, branch_code);
create index if not exists resources_code_idx   on public.resources (subject_code);

create table if not exists public.syllabus_links (
  id           bigint generated by default as identity primary key,
  branch_code  text not null,
  year         smallint not null check (year between 1 and 4),
  url          text not null,
  indexed_at   timestamptz,                    -- set when pushed into Pinecone
  unique (branch_code, year)
);

create table if not exists public.university_info (
  id          text primary key,                -- ordinances, gradingSystem, scholarship ...
  title       text not null,
  sort_order  int not null default 0,
  data        jsonb not null
);

-- ---------- Users (filled by Passport Google login) ----------

create table if not exists public.users (
  id             uuid primary key default gen_random_uuid(),
  google_id      text unique not null,
  email          text unique not null,
  name           text,
  avatar_url     text,
  role           text not null default 'student' check (role in ('student','admin')),
  branch_code    text references public.branches(code),
  year           smallint check (year between 1 and 4),
  semester       smallint check (semester between 1 and 8),
  onboarded_at   timestamptz,                  -- set when onboarding is finished
  display_name   text check (display_name is null or char_length(display_name) between 1 and 60),
  preferences    jsonb not null default '{}',  -- see src/lib/settings.ts
  created_at     timestamptz not null default now(),
  last_login_at  timestamptz not null default now()
);

